CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS outdoor_places (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    area TEXT NOT NULL,
    description TEXT NOT NULL,
    duration_minutes INTEGER NOT NULL CHECK (duration_minutes > 0),
    distance_km DOUBLE PRECISION NOT NULL CHECK (distance_km > 0),
    difficulty TEXT NOT NULL CHECK (difficulty IN ('easy','moderate','challenging')),
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    tags TEXT[] NOT NULL,
    scene TEXT NOT NULL,
    source_url TEXT NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    embedding_model TEXT NOT NULL,
    embedding VECTOR(384) NOT NULL
);
CREATE INDEX IF NOT EXISTS places_filters ON outdoor_places (difficulty, duration_minutes);
CREATE INDEX IF NOT EXISTS places_recorded ON outdoor_places (recorded_at);
-- Exact cosine search is deliberate for the small catalogue: perfect recall
-- after filtering. See docs/architecture.md before adding an ANN index.

CREATE TABLE IF NOT EXISTS walks (
    id UUID PRIMARY KEY,
    owner_hash TEXT NOT NULL,
    place_id BIGINT NOT NULL REFERENCES outdoor_places(id),
    minutes INTEGER NOT NULL CHECK (minutes BETWEEN 1 AND 1440),
    completed_on DATE NOT NULL,
    note TEXT NOT NULL DEFAULT '' CHECK (length(note) <= 500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS walks_owner_date ON walks (owner_hash, completed_on DESC);
